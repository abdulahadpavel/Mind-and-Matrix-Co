### 2. Highly granular campaign architecture

Campaigns were segmented by user intent (ethical tourism, elephant experiences, family activities) to maximize relevance and Quality Score. A controlled match-type strategy was applied — exact and phrase for core intent, supported by limited broad discovery. Top keywords were moved into SKAGs to further reduce CPC and improve ad relevance.

### 3. Conversion-focused ad copy testing

Ad creatives highlighted ethics, emotional connection and urgency, reinforcing the brand’s no-riding, ethical positioning. Continuous A/B testing of headlines and descriptions, combined with strong use of ad extensions, significantly improved CTR and SERP visibility.

